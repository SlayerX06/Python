# Fonksiyonlar = fonksiyonlar, belirli bir görevi yerine getiren kod bloklarıdır ve programlamada kodun yeniden kullanılabilirliğini sağlarlar.

def merhaba(ad, soyad, yas):
    print("Merhaba! " + ad + " " + soyad)
    print("Yaşınız: " + str(yas))
    print("Umarım iyisinizdir.")

merhaba("İbrahim", "Düşürge", 18)  # Fonksiyonu çağırır ve "Merhaba!" ile "Umarım iyisinizdir." yazdırır